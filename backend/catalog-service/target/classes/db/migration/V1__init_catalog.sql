CREATE TABLE categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(64) UNIQUE NOT NULL
);

CREATE TABLE products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand varchar(256) NOT NULL,
    category_id bigint NOT NULL REFERENCES categories(id),
    title varchar(256) NOT NULL,
    description text,
    price_retail numeric(12,2) NOT NULL,
    price_wholesale numeric(12,2) NOT NULL,
    wholesale_threshold integer NOT NULL DEFAULT 10,
    is_active BOOLEAN DEFAULT true
);

CREATE TABLE product_variants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    size varchar(32) NOT NULL,
    color varchar(32) NOT NULL,
    weight numeric(8,2) NOT NULL,
    sku varchar(128) UNIQUE,
    is_active BOOLEAN DEFAULT true
);

CREATE INDEX idx_products_category_id ON products(category_id);

CREATE TABLE discounts (
    category_id bigint PRIMARY KEY REFERENCES categories(id),
    discount numeric(3,2) NOT NULL
);

CREATE TABLE images (   
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    variant_id BIGINT NOT NULL REFERENCES product_variants(id),
    type VARCHAR(32) DEFAULT 'GALLERY',
    sort_order INT DEFAULT 0,     
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_images_variant_id ON images (variant_id);
